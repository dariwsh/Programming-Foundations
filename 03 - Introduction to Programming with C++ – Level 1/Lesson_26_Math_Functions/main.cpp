#include <iostream>
#include <cmath> // مكتبة الدوال الرياضية
using namespace std;

int main() {
    cout << "Square root of 16: " << sqrt(16) << endl;
    cout << "2 power 3: " << pow(2, 3) << endl;
    cout << "Round 2.6: " << round(2.6) << endl;
    cout << "Ceil 2.1: " << ceil(2.1) << endl;
    cout << "Floor 2.9: " << floor(2.9) << endl;
    return 0;
}