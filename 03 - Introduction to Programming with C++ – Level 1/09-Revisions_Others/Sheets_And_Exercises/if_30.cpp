#include <iostream>
#include <string>
using namespace std;

int main() {
    int numStudents;
    int passedCount = 0;
    int failedCount = 0;
    double classTotal = 0.0;
    
    // اطلب عدد الطلاب
    cout << "Enter the number of students: ";
    cin >> numStudents;
    
    // حلقة لإدخال بيانات كل طالب
    for (int i = 1; i <= numStudents; i++) {
        string name;
        double mark1, mark2, mark3;
        double average;
        string grade;
        
        cout << "\n--- Student " << i << " ---" << endl;
        
        // إدخال اسم الطالب
        cout << "Enter student's name: ";
        cin.ignore(); // لتنظيف الـ buffer
        getline(cin, name);
        
        // إدخال الدرجات الثلاث
        cout << "Enter mark 1: ";
        cin >> mark1;
        cout << "Enter mark 2: ";
        cin >> mark2;
        cout << "Enter mark 3: ";
        cin >> mark3;
        
        // حساب المتوسط
        average = (mark1 + mark2 + mark3) / 3.0;
        
        // إضافة المتوسط لمجموع الفصل
        classTotal += average;
        
        // تحديد التقدير باستخدام if-else
        if (average >= 90 && average <= 100) {
            grade = "Excellent";
        } else if (average >= 75 && average < 90) {
            grade = "Very Good";
        } else if (average >= 60 && average < 75) {
            grade = "Good";
        } else if (average >= 50 && average < 60) {
            grade = "Pass";
        } else {
            grade = "Fail";
        }
        
        // عد الطلاب الناجحين والراسبين
        if (average >= 50) {
            passedCount++; // استخدام increment operator
        } else {
            failedCount++; // استخدام increment operator
        }
        
        // طباعة نتيجة الطالب
        cout << "\nStudent: " << name << endl;
        cout << "Average: " << average << endl;
        cout << "Grade: " << grade << endl;
    }
    
    // حساب متوسط الفصل
    double classAverage = classTotal / numStudents;
    
    // طباعة النتائج النهائية
    cout << "\n========================================" << endl;
    cout << "========== FINAL STATISTICS ==========" << endl;
    cout << "========================================" << endl;
    cout << "Total students who passed: " << passedCount << endl;
    cout << "Total students who failed: " << failedCount << endl;
    cout << "Class average: " << classAverage << endl;
    cout << "========================================" << endl;
    
    return 0;
}